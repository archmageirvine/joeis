package irvine.math.group;

import java.util.Arrays;
import java.util.List;

/**
 * Exhaustive transitive actions on two or three blocks of a finite quotient
 * presented by its right Cayley graph. Every tested image respects all
 * generator edges, including the relations returning to the identity.
 * @author Gregory Morse
 */
final class RationalBlockQuotients {

  private RationalBlockQuotients() { }

  private static int[][] permutations(final int blocks) {
    return blocks == 2 ? new int[][] {{0, 1}, {1, 0}}
      : new int[][] {{0, 1, 2}, {0, 2, 1}, {1, 0, 2}, {1, 2, 0}, {2, 0, 1}, {2, 1, 0}};
  }

  private static int[] cycles(final int[] permutation) {
    final int[] out = new int[permutation.length];
    int count = 0;
    int used = 0;
    for (int i = 0; i < permutation.length; ++i) {
      if ((used & 1 << i) == 0) {
        int length = 0;
        for (int j = i; (used & 1 << j) == 0; j = permutation[j]) {
          used |= 1 << j;
          ++length;
        }
        out[count++] = length;
      }
    }
    final int[] result = Arrays.copyOf(out, count);
    Arrays.sort(result);
    return result;
  }

  static boolean excludes(final int[][] graph, final int blocks, final int[] locations, final List<int[]> traces,
                          final RationalBlockSpectra.LocalHull hull) {
    if (blocks < 2 || blocks > 3 || graph.length < 1 || locations.length != traces.size()) {
      return false;
    }
    final int rank = graph[0].length;
    final int[][] perms = permutations(blocks);
    final int m = perms.length;
    int combinations = 1;
    for (int j = 0; j < rank; ++j) {
      if (combinations > 250000 / m) {
        return false;
      }
      combinations *= m;
    }
    final int[][] mult = new int[m][m];
    final int[][] cycles = new int[m][];
    for (int i = 0; i < m; ++i) {
      cycles[i] = cycles(perms[i]);
      for (int j = 0; j < m; ++j) {
        final int[] p = new int[blocks];
        for (int k = 0; k < blocks; ++k) {
          p[k] = perms[j][perms[i][k]];
        }
        int index = 0;
        while (!Arrays.equals(p, perms[index])) {
          ++index;
        }
        mult[i][j] = index;
      }
    }
    final boolean[][] fits = new boolean[locations.length][m];
    for (int i = 0; i < fits.length; ++i) {
      for (int j = 0; j < m; ++j) {
        fits[i][j] = hull.fitsCycles(traces.get(i), cycles[j]);
      }
    }
    final int[] images = new int[graph.length];
    final int[] queue = new int[graph.length];
    final int[] generators = new int[rank];
    for (int code = 0; code < combinations; ++code) {
      int x = code;
      for (int i = 0; i < rank; ++i) {
        generators[i] = x % m;
        x /= m;
      }
      Arrays.fill(images, -1);
      images[0] = 0;
      int orbit = 1;
      int end = 1;
      boolean valid = true;
      for (int u = 0; u < end && valid; ++u) {
        final int row = queue[u];
        for (int j = 0; j < rank; ++j) {
          final int to = graph[row][j];
          final int next = mult[images[row]][generators[j]];
          if (images[to] < 0) {
            images[to] = next;
            orbit |= 1 << perms[next][0];
            queue[end++] = to;
          } else if (images[to] != next) {
            valid = false;
            break;
          }
        }
      }
      if (valid && end != graph.length) {
        throw new IllegalArgumentException("Block quotient is not generated by its edges");
      }
      if (valid && orbit == (1 << blocks) - 1) {
        for (int i = 0; i < locations.length && valid; ++i) {
          valid = fits[i][images[locations[i]]];
        }
        if (valid) {
          return false;
        }
      }
    }
    return true;
  }
}
