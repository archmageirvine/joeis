package irvine.oeis.a395;

import irvine.math.z.Z;
import irvine.oeis.AbstractSequence;

/**
 * A395424 Busy Beaver problem for FRACTRAN: a(n) is the maximal number of steps that a FRACTRAN program of size n can make on the integer 2 before eventually halting.
 * @author Gregory Morse
 */
public class A395424 extends AbstractSequence {

  private static final int[] PRIMES = {2, 3, 5, 7, 11};
  // Maximizing programs from Jason Yuen's census, not their step counts.
  private static final int[][][] WITNESSES = {
    {{1, 45}, {4, 5}, {3, 2}, {25, 3}},
    {{1, 45}, {4, 5}, {3, 2}, {125, 3}},
    {{5, 6}, {49, 2}, {3, 5}, {40, 7}},
    {{5, 6}, {49, 2}, {3, 5}, {80, 7}},
    {{5, 6}, {49, 2}, {3, 5}, {160, 7}},
    {{7, 15}, {22, 3}, {6, 77}, {5, 2}, {9, 5}},
    {{7, 15}, {4, 3}, {27, 14}, {5, 2}, {9, 5}},
  };

  private int mN = 1;

  /** Construct the sequence. */
  public A395424() {
    super(2);
  }

  private static int power(final int base, final int exponent) {
    int result = 1;
    for (int k = 0; k < exponent; ++k) {
      result *= base;
    }
    return result;
  }

  private static int[][] program(final int size) {
    if (size < 5) {
      return new int[][] {{power(3, size - 2), 2}};
    }
    if (size <= 10) {
      return new int[][] {{power(3, size - 4), 2}, {1, 3}};
    }
    if (size <= 14) {
      final int a = (size - 5) / 2;
      return new int[][] {{power(3, a), 2}, {power(5, size - 6 - a), 3}, {1, 5}};
    }
    if (size > WITNESSES.length + 14) {
      throw new UnsupportedOperationException("No checked FRACTRAN witness at this size");
    }
    return WITNESSES[size - 15];
  }

  private static int[][] exponentChanges(final int[][] fractions, final int expectedSize) {
    final int[][] rules = new int[fractions.length][PRIMES.length];
    int size = fractions.length;
    for (int k = 0; k < fractions.length; ++k) {
      int num = fractions[k][0];
      int den = fractions[k][1];
      for (int j = 0; j < PRIMES.length; ++j) {
        final int p = PRIMES[j];
        while (num % p == 0) {
          ++rules[k][j];
          num /= p;
        }
        while (den % p == 0) {
          --rules[k][j];
          den /= p;
        }
        size += Math.abs(rules[k][j]);
      }
      if (num != 1 || den != 1) {
        throw new IllegalStateException("FRACTRAN witness has an unsupported prime factor");
      }
    }
    if (size != expectedSize) {
      throw new IllegalStateException("Incorrect FRACTRAN witness size");
    }
    return rules;
  }

  private static long run(final int[][] rules) {
    final long[] state = new long[PRIMES.length];
    state[0] = 1; // The input is 2.
    long steps = 0;
    while (true) {
      int selected = -1;
      long repeat = 0;
      for (int k = 0; k < rules.length; ++k) {
        repeat = Long.MAX_VALUE;
        for (int j = 0; j < state.length; ++j) {
          if (rules[k][j] < 0) {
            repeat = Math.min(repeat, state[j] / -rules[k][j]);
          }
        }
        if (repeat > 0) {
          selected = k;
          break;
        }
      }
      if (selected < 0) {
        return steps;
      }
      final int[] move = rules[selected];
      for (int k = 0; k < selected; ++k) {
        // Intersect the times at which this earlier fraction is enabled
        // along the arithmetic progression generated by move.
        long lo = 1;
        long hi = repeat;
        for (int j = 0; j < state.length && lo <= hi; ++j) {
          if (rules[k][j] < 0) {
            final long deficit = -rules[k][j] - state[j];
            if (move[j] > 0 && deficit > 0) {
              lo = Math.max(lo, 1 + (deficit - 1) / move[j]);
            } else if (move[j] <= 0 && deficit > 0) {
              hi = 0;
            } else if (move[j] < 0) {
              hi = Math.min(hi, (-deficit) / -move[j]);
            }
          }
        }
        if (lo <= hi) {
          repeat = lo;
        }
      }
      if (repeat == Long.MAX_VALUE) {
        throw new IllegalStateException("FRACTRAN witness does not halt");
      }
      for (int j = 0; j < state.length; ++j) {
        state[j] = Math.addExact(state[j], Math.multiplyExact(repeat, move[j]));
      }
      steps = Math.addExact(steps, repeat);
      if (steps > 100_000_000L) {
        throw new IllegalStateException("FRACTRAN witness exceeded the finite verification range");
      }
    }
  }

  @Override
  public Z next() {
    // The independent census proves maximality through size 21. Here
    // we only check the size and compute the attaining program's run.
    return Z.valueOf(run(exponentChanges(program(++mN), mN)));
  }
}
