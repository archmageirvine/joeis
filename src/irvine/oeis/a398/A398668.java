package irvine.oeis.a398;

import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Objects;
import java.util.Set;

import irvine.math.z.Z;
import irvine.oeis.Sequence1;

/**
 * A398668 allocated for Jean Lauro Muller.
 * @author Sean A. Irvine
 */
public class A398668 extends Sequence1 {

  // After Jean Lauro Muller

  private int mN = 0;

  @Override
  public Z next() {
    if (++mN > 16) {
      throw new UnsupportedOperationException();
    }
    if (mN == 0 || mN == 1) {
      return Z.ONE;
    }

    final List<long[]> perms = new ArrayList<>();
    generatePermutations(mN, 0, new int[mN], new boolean[mN], perms);
    final Set<Key> classes = new HashSet<>();
    for (final long[] pp0 : perms) {
      for (final long[] pp1 : perms) {
        final long p0 = pp0[0];
        final long p1 = pp1[0];
        if (!transitive(p0, p1, mN)) {
          continue;
        }
        // comp[i] = p0[p1[i]]
        final long comp = compose(p0, p1, mN);
        final long pinf = inverse(comp, mN);
        final String c0 = cycleType(p0, mN);
        final String c1 = cycleType(p1, mN);
        final String cinf = cycleType(pinf, mN);
        final int gord = groupOrder(p0, p1, mN);
        classes.add(new Key(c0, c1, cinf, gord));
      }
    }

    return Z.valueOf(classes.size());
  }

  /*
   * Generate all permutations of 0..n-1 in packed form.
   */
  private static void generatePermutations(final int n, final int pos, final int[] p, final boolean[] used, final List<long[]> result) {
    if (pos == n) {
      result.add(new long[] {encode(p)});
      return;
    }

    for (int i = 0; i < n; ++i) {
      if (!used[i]) {
        used[i] = true;
        p[pos] = i;
        generatePermutations(n, pos + 1, p, used, result);
        used[i] = false;
      }
    }
  }

  /*
   * Encode a permutation using four bits per entry.
   *
   * This is sufficient for the values normally encountered in this
   * sequence (n <= 16).
   */
  private static long encode(final int[] p) {
    long x = 0;
    for (int i = 0; i < p.length; ++i) {
      x |= ((long) p[i]) << (4 * i);
    }
    return x;
  }

  private static int image(final long p, final int i) {
    return (int) ((p >>> (4 * i)) & 15L);
  }

  /*
   * Return p0 o p1, i.e. (p0 o p1)(i) = p0(p1(i)).
   */
  private static long compose(final long p0, final long p1, final int n) {
    long result = 0;
    for (int i = 0; i < n; ++i) {
      final int x = image(p1, i);
      final int y = image(p0, x);
      result |= ((long) y) << (4 * i);
    }
    return result;
  }

  /*
   * Invert a permutation.
   */
  private static long inverse(final long p, final int n) {
    long result = 0;
    for (int i = 0; i < n; ++i) {
      result |= ((long) i) << (4 * image(p, i));
    }
    return result;
  }

  /*
   * Test whether the group generated by p0 and p1 acts transitively.
   *
   * Since p0 and p1 are permutations, it is enough to find the orbit
   * of 0 under the two generators.
   */
  private static boolean transitive(final long p0, final long p1, final int n) {
    final boolean[] vis = new boolean[n];
    final int[] stack = new int[n];
    int top = 0;
    int count = 0;

    vis[0] = true;
    stack[top++] = 0;

    while (top != 0) {
      final int x = stack[--top];
      ++count;

      final int y0 = image(p0, x);
      if (!vis[y0]) {
        vis[y0] = true;
        stack[top++] = y0;
      }

      final int y1 = image(p1, x);
      if (!vis[y1]) {
        vis[y1] = true;
        stack[top++] = y1;
      }
    }

    return count == n;
  }

  /*
   * Return the cycle type as a canonical string, with parts in
   * decreasing order, matching the Python tuple(sorted(..., reverse=True)).
   */
  private static String cycleType(final long p, final int n) {
    final boolean[] vis = new boolean[n];
    final int[] lengths = new int[n];
    int number = 0;
    for (int i = 0; i < n; ++i) {
      if (!vis[i]) {
        int c = 0;
        int j = i;
        while (!vis[j]) {
          vis[j] = true;
          j = image(p, j);
          ++c;
        }
        lengths[number++] = c;
      }
    }

    Arrays.sort(lengths, 0, number);
    final StringBuilder sb = new StringBuilder();
    sb.append('(');
    for (int i = number - 1; i >= 0; --i) {
      if (i != number - 1) {
        sb.append(',');
      }
      sb.append(lengths[i]);
    }
    sb.append(')');
    return sb.toString();
  }

  /*
   * Compute the order of the group generated by p0 and p1.
   *
   * Starting with the identity, repeatedly multiply on the right by
   * p0 and p1:
   *
   *     c -> c o p0
   *     c -> c o p1
   *
   * which is exactly the operation
   *
   *     tuple(c[g[i]] for i in range(n))
   *
   * in the Python code.
   */
  private static int groupOrder(final long p0, final long p1, final int n) {
    final long identity = identity(n);
    final Set<Long> group = new HashSet<>();
    final ArrayDeque<Long> queue = new ArrayDeque<>();

    group.add(identity);
    queue.add(identity);

    while (!queue.isEmpty()) {
      final long c = queue.remove();
      final long next0 = compose(c, p0, n);
      if (group.add(next0)) {
        queue.add(next0);
      }
      final long next1 = compose(c, p1, n);
      if (group.add(next1)) {
        queue.add(next1);
      }
    }

    return group.size();
  }

  private static long identity(final int n) {
    long result = 0;
    for (int i = 0; i < n; ++i) {
      result |= ((long) i) << (4 * i);
    }
    return result;
  }

  private static final class Key {
    private final String mC0;
    private final String mC1;
    private final String mCinf;
    private final int mOrder;

    Key(final String c0, final String c1, final String cinf, final int order) {
      mC0 = c0;
      mC1 = c1;
      mCinf = cinf;
      mOrder = order;
    }

    @Override
    public int hashCode() {
      return Objects.hash(mC0, mC1, mCinf, mOrder);
    }

    @Override
    public boolean equals(final Object obj) {
      if (this == obj) {
        return true;
      }
      if (!(obj instanceof Key)) {
        return false;
      }
      final Key other = (Key) obj;
      return mOrder == other.mOrder && mC0.equals(other.mC0) && mC1.equals(other.mC1) && mCinf.equals(other.mCinf);
    }
  }
}
