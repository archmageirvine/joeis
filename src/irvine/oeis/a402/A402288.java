package irvine.oeis.a402;

import java.util.ArrayList;
import java.util.List;

import irvine.math.z.Z;
import irvine.oeis.Sequence1;

/**
 * A402288 Triangle read by rows: among the lists of n positive integers that contain no earlier row as a subsequence, row n has the smallest possible largest term and, among those, is the lexicographically smallest.
 * @author Sean A. Irvine
 */
public class A402288 extends Sequence1 {

  // After Alper Ferudun

  private final List<int[]> mRows = new ArrayList<>();
  private int mN = 1;
  private int mM = 0;

  /**
   * Recursive search for the next row.
   * @param v current constraint rows
   * @param left number of entries still to choose
   * @param tight whether the current prefix is constrained by floor
   * @param floor lower-bound row
   * @return a row, or null if no solution exists
   */
  private int[] find(final List<int[]> v, final int left, final boolean tight, final int[] floor) {

    // An empty constraint makes the state impossible.
    for (final int[] t : v) {
      if (t.length == 0) {
        return null;
      }
    }

    if (left == 0) {
      return new int[0];
    }

    // Retain only constraints that can still affect this search.
    final List<int[]> constraints = new ArrayList<>();
    for (final int[] t : v) {
      if (t.length <= left) {
        constraints.add(t);
      }
    }

    // Maximum number of occurrences of each colour that can be
    // appended without violating the corresponding constraints.
    final int[] caps = new int[mN];
    for (int c = 1; c <= mN; ++c) {
      int cap = left;
      for (final int[] t : constraints) {
        boolean allC = true;
        for (final int x : t) {
          if (x != c) {
            allC = false;
            break;
          }
        }
        if (allC) {
          cap = Math.min(cap, t.length - 1);
        }
      }
      caps[c - 1] = cap;
    }

    int total = 0;
    for (final int cap : caps) {
      total += cap;
    }
    if (total < left) {
      return null;
    }

    final int depth = mRows.size() + 1 - left;
    for (int c = 1; c <= mN; ++c) {
      if (caps[c - 1] == 0) {
        continue;
      }
      if (tight && c < floor[depth]) {
        continue;
      }
      final boolean nextTight = tight && c == floor[depth] && depth + 1 < floor.length;
      // Apply the chosen colour to each constraint.
      final List<int[]> nextConstraints = new ArrayList<>();
      for (final int[] t : constraints) {
        if (t[0] == c) {
          final int[] tail = new int[t.length - 1];
          System.arraycopy(t, 1, tail, 0, tail.length);
          nextConstraints.add(tail);
        } else {
          nextConstraints.add(t);
        }
      }
      final int[] tail = find(nextConstraints, left - 1, nextTight, floor);
      if (tail != null) {
        final int[] result = new int[tail.length + 1];
        result[0] = c;
        System.arraycopy(tail, 0, result, 1, tail.length);
        return result;
      }
    }
    return null;
  }

  @Override
  public Z next() {
    // Stop after the 13 rows generated by the original Python.
    if (mRows.size() == 13) {
      return null;
    }

    // Generate a new row when the previous one has been emitted.
    if (mRows.isEmpty() || mM == mRows.get(mRows.size() - 1).length) {
      mM = 0;
      while (true) {
        final int[] floor;
        if (!mRows.isEmpty()) {
          final int[] last = mRows.get(mRows.size() - 1);
          int max = 0;
          for (final int x : last) {
            max = Math.max(max, x);
          }
          floor = max == mN ? last : new int[0];
        } else {
          floor = new int[0];
        }
        final int[] row = find(mRows, mRows.size() + 1, floor.length != 0, floor);

        if (row == null) {
          ++mN;
        } else {
          mRows.add(row);
          break;
        }
      }
    }
    return Z.valueOf(mRows.get(mRows.size() - 1)[mM++]);
  }
}
